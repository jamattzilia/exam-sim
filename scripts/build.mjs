// Builds dist/exam-sim.html (the whole app in one file that opens with a double-click)
// and sw.js (the offline cache for the hosted site).
// Browsers refuse to load ES modules from file://, so the modules are bundled into a
// single classic <script>, each wrapped in its own function scope.
//
//   node scripts/build.mjs           write dist/exam-sim.html
//   node scripts/build.mjs --check   exit 1 if dist/exam-sim.html is out of date
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const outFile = join(root, "dist", "exam-sim.html");

const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*"([^"]+)";?[ \t]*$/gm;
const EXPORT_RE = /^export\s+(?:async\s+)?(const|let|function)\s+([A-Za-z_$][\w$]*)/gm;

function loadModules(entry) {
  const ordered = [];
  const seen = new Set();
  const visit = (file) => {
    if (seen.has(file)) return;
    seen.add(file);
    const source = readFileSync(file, "utf8");
    const imports = [...source.matchAll(IMPORT_RE)].map((m) => ({
      names: m[1].split(",").map((n) => n.trim()).filter(Boolean),
      file: resolve(dirname(file), m[2]),
    }));
    imports.forEach((i) => visit(i.file));
    ordered.push({ file, source, imports });
  };
  visit(entry);
  return ordered;
}

const varName = (file) => "__mod_" + relative(root, file).replace(/[^\w]/g, "_");

function bundle(modules) {
  return modules
    .map(({ file, source, imports }) => {
      const exports = [...source.matchAll(EXPORT_RE)].map((m) => m[2]);
      let body = source.replace(IMPORT_RE, "").replace(/^export\s+/gm, "");
      const leftover = body.match(/^\s*(import|export)\b.*$/m);
      if (leftover) throw new Error(`${relative(root, file)}: unsupported module syntax: ${leftover[0].trim()}`);
      const header = imports
        .map(({ names, file: dep }) => {
          const bindings = names.map((n) => n.replace(/\s+as\s+/, ": ")).join(", ");
          return `  const { ${bindings} } = ${varName(dep)};`;
        })
        .join("\n");
      // No re-indenting: it would change the contents of multi-line template literals.
      return `// ${relative(root, file)}\nconst ${varName(file)} = (() => {\n${header ? header + "\n" : ""}${body.trim()}\nreturn { ${exports.join(", ")} };\n})();`;
    })
    .join("\n\n");
}

// Inline <script>/<style> contents must not contain their own closing tag (question
// text includes a sample "<script>" XSS payload) or an HTML comment opener.
const escapeForInline = (code, tag) => code.replace(new RegExp(`</(${tag})`, "gi"), "<\\/$1").replace(/<!--/g, "<\\!--");

const HEAD_LINKS = {
  manifest: '<link rel="manifest" href="manifest.webmanifest" />',
  icon: '<link rel="icon" href="icons/icon.svg" type="image/svg+xml" />',
  appleIcon: '<link rel="apple-touch-icon" href="icons/icon-180.png" />',
};

export function build() {
  const html = readFileSync(join(root, "index.html"), "utf8");
  const css = readFileSync(join(root, "css", "styles.css"), "utf8");
  const js = bundle(loadModules(join(root, "js", "main.js")));
  const iconSvg = readFileSync(join(root, "icons", "icon.svg"), "utf8");

  const cssTag = '<link rel="stylesheet" href="css/styles.css" />';
  const jsTag = '<script type="module" src="js/main.js"></script>';
  for (const tag of [cssTag, jsTag, ...Object.values(HEAD_LINKS)]) {
    if (!html.includes(tag)) throw new Error(`index.html no longer contains: ${tag}`);
  }

  // The single file has no files beside it: drop the manifest (which also turns off
  // service-worker registration) and inline the favicon.
  return html
    .replace(cssTag, () => `<style>\n${escapeForInline(css, "style")}</style>`)
    .replace(jsTag, () => `<script>\n"use strict";\n${escapeForInline(js, "script")}\n</script>`)
    .replace(`${HEAD_LINKS.manifest}\n  `, "")
    .replace(`${HEAD_LINKS.appleIcon}\n  `, "")
    .replace(HEAD_LINKS.icon, `<link rel="icon" href="data:image/svg+xml,${encodeURIComponent(iconSvg.replace(/<!--[\s\S]*?-->/g, "").trim())}" />`)
    .replace("<head>", "<head>\n  <!-- Generated by scripts/build.mjs from index.html, css/ and js/. Do not edit by hand. -->");
}

// sw.js precaches every file the site needs. Its cache name is a hash of their
// contents, so any change to the site produces a new worker that swaps the whole
// cache at once (never a mix of old and new files).
export function buildServiceWorker() {
  const modules = loadModules(join(root, "js", "main.js")).map((m) => relative(root, m.file).split(sep).join("/"));
  const files = ["index.html", "css/styles.css", ...modules, "manifest.webmanifest", "icons/icon.svg", "icons/icon-180.png", "icons/icon-192.png", "icons/icon-512.png"];
  const hash = createHash("sha256");
  for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
  const version = hash.digest("hex").slice(0, 12);
  const assets = ["./", ...files];
  return `// Generated by scripts/build.mjs. Do not edit by hand.
const CACHE = "exam-sim-${version}";
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("exam-sim-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Cache first for this site's files (they change together with the worker); anything
// else goes to the network untouched.
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(caches.match(request, { ignoreSearch: true }).then((cached) => cached || fetch(request)));
});
`;
}

const outputs = [
  [outFile, build()],
  [join(root, "sw.js"), buildServiceWorker()],
];
if (process.argv.includes("--check")) {
  const stale = outputs.filter(([file, content]) => !existsSync(file) || readFileSync(file, "utf8") !== content);
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([f]) => relative(root, f)).join(", ")}. Run: npm run build`);
    process.exit(1);
  }
  console.log("dist/exam-sim.html and sw.js are up to date.");
} else {
  for (const [file, content] of outputs) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`Wrote ${relative(root, file)} (${(content.length / 1024).toFixed(0)} KB)`);
  }
}
